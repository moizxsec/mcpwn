/**
 * Shell completion scripts (§Phase-8/F1). `mcpwn completions <bash|zsh|fish>`
 * prints a completion script to stdout — pipe it into your shell's completion
 * dir, or source it. Pure string builders, zero deps.
 *
 * The command/flag lists are kept here (mirroring the HELP block in cli.ts) so a
 * single source drives the scripts; a unit test asserts each shell mentions the
 * subcommands, catching an empty/broken emit.
 */

export const SUBCOMMANDS = [
  "http",
  "baseline",
  "pin",
  "replay",
  "scan",
  "report",
  "advisory",
  "payloads",
  "templates",
  "wrap",
  "unwrap",
  "init",
  "completions",
  "badge",
  "man",
] as const;

/** Top-level flags for the stdio proxy (the default, no-subcommand invocation). */
export const GLOBAL_FLAGS = [
  "-i",
  "--intercept",
  "-r",
  "--rule",
  "--template",
  "-l",
  "--log",
  "-v",
  "--verbose",
  "-h",
  "--help",
  "--version",
  "--config",
  "--no-auto-config",
  "--detector",
  "--rule-plugin",
  "--guard",
  "--policy",
  "--findings-out",
  "--baseline",
  "--baseline-capture",
  "--pin",
  "--taint",
  "--redact",
  "--redact-file",
  "--scope-method",
  "--scope-tool",
  "--scope-direction",
  "--only-tampered",
  "--scope-affects-log",
] as const;

export const WRAP_CLIENTS = ["claude-desktop", "cursor", "cline", "vscode", "windsurf"] as const;

export const COMPLETION_SHELLS = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

export function isCompletionShell(s: string): s is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(s);
}

function bashScript(): string {
  const subs = SUBCOMMANDS.join(" ");
  const flags = GLOBAL_FLAGS.join(" ");
  const clients = WRAP_CLIENTS.join(" ");
  return `# bash completion for mcpwn — generated by \`mcpwn completions bash\`
# Install: mcpwn completions bash > /etc/bash_completion.d/mcpwn
#     or:  mcpwn completions bash > ~/.local/share/bash-completion/completions/mcpwn
_mcpwn() {
  local cur prev words cword
  _init_completion 2>/dev/null || {
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"
  }
  local subcommands="${subs}"
  local flags="${flags}"
  local clients="${clients}"

  case "\${prev}" in
    --client) COMPREPLY=( $(compgen -W "\${clients}" -- "\${cur}") ); return ;;
    completions) COMPREPLY=( $(compgen -W "bash zsh fish" -- "\${cur}") ); return ;;
    --scope-direction) COMPREPLY=( $(compgen -W "c2s s2c" -- "\${cur}") ); return ;;
    --fail-on) COMPREPLY=( $(compgen -W "critical high medium low info" -- "\${cur}") ); return ;;
  esac

  if [[ "\${cur}" == -* ]]; then
    COMPREPLY=( $(compgen -W "\${flags}" -- "\${cur}") )
    return
  fi

  if [[ \${COMP_CWORD} -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "\${subcommands}" -- "\${cur}") )
    return
  fi
  COMPREPLY=( $(compgen -f -- "\${cur}") )
}
complete -F _mcpwn mcpwn
`;
}

function zshScript(): string {
  const subs = SUBCOMMANDS.join(" ");
  const flags = GLOBAL_FLAGS.join(" ");
  const clients = WRAP_CLIENTS.join(" ");
  return `#compdef mcpwn
# zsh completion for mcpwn — generated by \`mcpwn completions zsh\`
# Install: mcpwn completions zsh > "\${fpath[1]}/_mcpwn"  (then restart zsh)
_mcpwn() {
  local -a subcommands flags clients
  subcommands=(${subs})
  flags=(${flags})
  clients=(${clients})

  case "\${words[CURRENT-1]}" in
    --client) compadd -- \${clients}; return ;;
    completions) compadd -- bash zsh fish; return ;;
    --scope-direction) compadd -- c2s s2c; return ;;
    --fail-on) compadd -- critical high medium low info; return ;;
  esac

  if [[ "\${words[CURRENT]}" == -* ]]; then
    compadd -- \${flags}
    return
  fi
  if (( CURRENT == 2 )); then
    compadd -- \${subcommands}
    return
  fi
  _files
}
compdef _mcpwn mcpwn
`;
}

function fishScript(): string {
  const lines: string[] = [];
  lines.push("# fish completion for mcpwn — generated by `mcpwn completions fish`");
  lines.push("# Install: mcpwn completions fish > ~/.config/fish/completions/mcpwn.fish");
  lines.push("function __mcpwn_no_subcommand");
  lines.push("    set -l cmd (commandline -opc)");
  lines.push("    if test (count $cmd) -eq 1");
  lines.push("        return 0");
  lines.push("    end");
  lines.push("    return 1");
  lines.push("end");
  for (const s of SUBCOMMANDS) {
    lines.push(
      `complete -c mcpwn -n '__mcpwn_no_subcommand' -f -a '${s}' -d 'mcpwn ${s} subcommand'`
    );
  }
  // A few representative flags (fish shows these everywhere).
  lines.push("complete -c mcpwn -l help -s h -d 'Show help'");
  lines.push("complete -c mcpwn -l version -d 'Print version'");
  lines.push("complete -c mcpwn -l verbose -s v -d 'Verbose output'");
  lines.push("complete -c mcpwn -l intercept -s i -d 'Interactive intercept'");
  lines.push("complete -c mcpwn -l rule -s r -r -d 'Load a tamper-rule file'");
  lines.push("complete -c mcpwn -l findings-out -r -d 'Write findings dir on exit'");
  lines.push("complete -c mcpwn -l guard -d 'Run as a defensive firewall'");
  lines.push(
    `complete -c mcpwn -n '__fish_seen_subcommand_from wrap unwrap init' -l client -x -a '${WRAP_CLIENTS.join(
      " "
    )}' -d 'MCP client'`
  );
  lines.push(
    "complete -c mcpwn -n '__fish_seen_subcommand_from completions' -f -a 'bash zsh fish' -d 'Shell'"
  );
  return lines.join("\n") + "\n";
}

/** Emit a completion script for the given shell. */
export function generateCompletions(shell: CompletionShell): string {
  switch (shell) {
    case "bash":
      return bashScript();
    case "zsh":
      return zshScript();
    case "fish":
      return fishScript();
  }
}

/** `mcpwn completions <bash|zsh|fish>` — prints the script to stdout. */
export function runCompletions(argv: string[]): number {
  const shell = argv[0];
  if (!shell) {
    process.stderr.write(
      `mcpwn completions: missing shell (use one of: ${COMPLETION_SHELLS.join(", ")})\n`
    );
    return 2;
  }
  if (!isCompletionShell(shell)) {
    process.stderr.write(
      `mcpwn completions: unknown shell "${shell}" (use one of: ${COMPLETION_SHELLS.join(", ")})\n`
    );
    return 2;
  }
  process.stdout.write(generateCompletions(shell));
  return 0;
}
